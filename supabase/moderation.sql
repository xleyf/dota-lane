-- Run after schema.sql, forum.sql, and guide_feedback.sql.
-- Existing public rows stay visible. New guide/forum posts wait for review.

alter table public.guides
  add column if not exists moderation_status text not null default 'approved';
alter table public.guides
  drop constraint if exists guides_moderation_status_check;
alter table public.guides
  add constraint guides_moderation_status_check
  check (moderation_status in ('pending', 'approved', 'rejected'));
alter table public.guides alter column moderation_status set default 'pending';

alter table public.forum_threads
  add column if not exists moderation_status text not null default 'approved';
alter table public.forum_threads
  drop constraint if exists forum_threads_moderation_status_check;
alter table public.forum_threads
  add constraint forum_threads_moderation_status_check
  check (moderation_status in ('pending', 'approved', 'rejected'));
alter table public.forum_threads alter column moderation_status set default 'pending';

alter table public.forum_replies
  add column if not exists moderation_status text not null default 'approved';
alter table public.forum_replies
  drop constraint if exists forum_replies_moderation_status_check;
alter table public.forum_replies
  add constraint forum_replies_moderation_status_check
  check (moderation_status in ('pending', 'approved', 'rejected'));
alter table public.forum_replies alter column moderation_status set default 'pending';

drop policy if exists "Guides are public" on public.guides;
create policy "Approved guides are public" on public.guides
  for select to anon, authenticated using (moderation_status = 'approved');
drop policy if exists "Visitors can publish guides" on public.guides;
drop policy if exists "Visitors can submit guides" on public.guides;
create policy "Visitors can submit guides for review" on public.guides
  for insert to anon, authenticated with check (
    moderation_status = 'pending'
    and char_length(trim(title)) between 1 and 80
    and char_length(trim(hero)) between 1 and 80
    and (position is null or position between 1 and 5)
    and char_length(description) <= 180
    and (steam_url like 'https://steamcommunity.com/%'
      or steam_url like 'https://www.steamcommunity.com/%')
  );

drop policy if exists "Forum threads are public" on public.forum_threads;
create policy "Approved forum threads are public" on public.forum_threads
  for select to anon, authenticated using (moderation_status = 'approved');
drop policy if exists "Visitors can create forum threads" on public.forum_threads;
create policy "Visitors can submit forum threads for review" on public.forum_threads
  for insert to anon, authenticated with check (
    moderation_status = 'pending'
    and char_length(trim(title)) between 5 and 120
    and char_length(trim(body)) between 5 and 2000
    and category in ('Вопрос', 'Матчап', 'Предметы', 'Тактика')
  );

drop policy if exists "Forum replies are public" on public.forum_replies;
create policy "Approved forum replies are public" on public.forum_replies
  for select to anon, authenticated using (moderation_status = 'approved');
drop policy if exists "Visitors can reply to forum threads" on public.forum_replies;
create policy "Visitors can submit replies for review" on public.forum_replies
  for insert to anon, authenticated with check (
    moderation_status = 'pending'
    and char_length(trim(body)) between 1 and 1200
    and exists (
      select 1 from public.forum_threads t
      where t.id = thread_id and t.moderation_status = 'approved'
    )
  );

create table if not exists public.content_reports (
  id bigint generated by default as identity primary key,
  target_type text not null check (target_type in ('steam_build', 'community_guide', 'forum_thread', 'forum_reply')),
  target_id text not null check (char_length(trim(target_id)) between 1 and 80),
  reason text not null check (reason in ('Оскорбления или грубость', 'Спам или реклама', 'Неверный герой или ссылка', 'Другое')),
  details text not null default '' check (char_length(details) <= 500),
  visitor_id uuid not null,
  status text not null default 'new' check (status in ('new', 'reviewed', 'dismissed')),
  created_at timestamptz not null default now(),
  unique (target_type, target_id, visitor_id)
);

alter table public.content_reports enable row level security;
revoke all on table public.content_reports from anon, authenticated;
grant insert on table public.content_reports to anon, authenticated;
grant usage, select on sequence public.content_reports_id_seq to anon, authenticated;
drop policy if exists "Visitors can report public content" on public.content_reports;
create policy "Visitors can report public content" on public.content_reports
  for insert to anon, authenticated with check (
    char_length(trim(target_id)) between 1 and 80
    and char_length(details) <= 500
    and status = 'new'
  );

create index if not exists guides_moderation_status_created_idx
  on public.guides (moderation_status, created_at desc);
create index if not exists forum_threads_moderation_status_created_idx
  on public.forum_threads (moderation_status, created_at desc);
create index if not exists forum_replies_moderation_status_thread_idx
  on public.forum_replies (moderation_status, thread_id, created_at);
create index if not exists content_reports_status_created_idx
  on public.content_reports (status, created_at desc);

