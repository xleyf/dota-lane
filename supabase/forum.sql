create table if not exists public.forum_replies (
  id bigint generated by default as identity primary key,
  thread_id bigint not null references public.forum_threads(id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 1200),
  created_at timestamptz not null default now()
);

alter table public.forum_threads enable row level security;
alter table public.forum_replies enable row level security;
revoke all on table public.forum_threads, public.forum_replies from anon, authenticated;
grant select, insert on table public.forum_threads, public.forum_replies to anon, authenticated;

drop policy if exists "Forum threads are public" on public.forum_threads;
create policy "Forum threads are public" on public.forum_threads
  for select to anon, authenticated using (true);
drop policy if exists "Visitors can create forum threads" on public.forum_threads;
create policy "Visitors can create forum threads" on public.forum_threads
  for insert to anon, authenticated with check (
    char_length(trim(title)) between 5 and 120
    and char_length(trim(body)) between 5 and 2000
    and category in ('Вопрос','Матчап','Предметы','Тактика')
  );
drop policy if exists "Forum replies are public" on public.forum_replies;
create policy "Forum replies are public" on public.forum_replies
  for select to anon, authenticated using (true);
drop policy if exists "Visitors can reply to forum threads" on public.forum_replies;
create policy "Visitors can reply to forum threads" on public.forum_replies
  for insert to anon, authenticated with check (char_length(trim(body)) between 1 and 1200);
