grant select, insert on table public.guides to anon, authenticated;

drop policy if exists "Guides are public" on public.guides;
create policy "Guides are public"
  on public.guides for select to anon, authenticated
  using (true);

drop policy if exists "Visitors can submit guides" on public.guides;
create policy "Visitors can submit guides"
  on public.guides for insert to anon, authenticated
  with check (
    char_length(title) between 3 and 80
    and char_length(description) <= 180
    and steam_url ~ '^https://(www\.)?steamcommunity\.com/'
  );

