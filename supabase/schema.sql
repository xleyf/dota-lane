-- Run first in the Supabase SQL Editor to create the shared guide feed.
create table if not exists public.guides (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(trim(title)) between 1 and 80),
  hero text not null check (char_length(trim(hero)) between 1 and 80),
  position smallint null check (position is null or position between 1 and 5),
  description text not null default '' check (char_length(description) <= 180),
  steam_url text not null check (steam_url ~ '^https://(www\.)?steamcommunity\.com/'),
  created_at timestamptz not null default now()
);

alter table public.guides enable row level security;
revoke all on table public.guides from anon, authenticated;
grant select, insert on table public.guides to anon, authenticated;
grant usage, select on sequence public.guides_id_seq to anon, authenticated;

drop policy if exists "Guides are public" on public.guides;
create policy "Guides are public" on public.guides
  for select to anon, authenticated using (true);

drop policy if exists "Visitors can publish guides" on public.guides;
create policy "Visitors can publish guides" on public.guides
  for insert to anon, authenticated with check (
    char_length(trim(title)) between 1 and 80
    and char_length(trim(hero)) between 1 and 80
    and (position is null or position between 1 and 5)
    and char_length(description) <= 180
    and steam_url ~ '^https://(www\.)?steamcommunity\.com/'
  );
